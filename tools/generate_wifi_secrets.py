"""Generate the ESP32 credential header from the project's local .env file."""
from pathlib import Path
import json
import sys
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parent.parent
ENV_FILE = ROOT / ".env"
HEADER = ROOT / "visrodeck_kiosk" / "wifi_secrets.h"


def read_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    for line_number, raw in enumerate(path.read_text(encoding="utf-8-sig").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[7:].lstrip()
        if "=" not in line:
            raise ValueError(f"{path.name}:{line_number}: expected KEY=VALUE")
        key, value = line.split("=", 1)
        key, value = key.strip(), value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        values[key] = value
    return values


def main() -> int:
    if not ENV_FILE.is_file():
        print("Missing .env. Copy .env.example to .env and set WIFI_SSID and WIFI_PASSWORD.", file=sys.stderr)
        return 1
    values = read_env(ENV_FILE)
    ssid, password = values.get("WIFI_SSID", ""), values.get("WIFI_PASSWORD", "")
    server_url = values.get("KIOSK_SERVER_URL", "").rstrip("/")
    missing = [name for name, value in (
        ("WIFI_SSID", ssid),
        ("WIFI_PASSWORD", password),
        ("KIOSK_SERVER_URL", server_url),
    ) if not value]
    if missing:
        print(f"Set {', '.join(missing)} in .env before generating the ESP32 config.", file=sys.stderr)
        return 1

    parsed_url = urlsplit(server_url)
    if parsed_url.scheme != "http" or not parsed_url.hostname or parsed_url.path not in ("", "/"):
        print("KIOSK_SERVER_URL must be the laptop URL, e.g. http://192.168.43.25:8000", file=sys.stderr)
        return 1

    # json.dumps produces escaped string literals accepted by the C++ compiler.
    content = (
        "// Generated by tools/generate_wifi_secrets.py from .env. Do not commit credentials.\n"
        "#pragma once\n"
        f"#define VISRODECK_WIFI_SSID {json.dumps(ssid, ensure_ascii=True)}\n"
        f"#define VISRODECK_WIFI_PASSWORD {json.dumps(password, ensure_ascii=True)}\n"
        f"#define VISRODECK_SERVER_BASE_URL {json.dumps(server_url, ensure_ascii=True)}\n"
    )
    HEADER.write_text(content, encoding="utf-8")
    print("Generated visrodeck_kiosk/wifi_secrets.h with Wi-Fi and server settings. You can now compile the kiosk sketch.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
